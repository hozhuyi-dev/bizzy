package integrity

import (
	"fmt"
	"strings"

	"bizzy-lambda/internal/features/book"
)

// Table renders the link rules as Markdown, known gaps first, for review.
func Table() string {
	var b strings.Builder
	b.WriteString("# Links between entities\n\n")
	b.WriteString("Generated by the integrity test (`go test ./internal/integrity -update`); do not edit.\n\n")

	b.WriteString("## Known gaps\n\nChecked and reported, but not yet made to hold: each awaits a decision on the suggested resolution.\n\n")
	gaps := 0
	for _, r := range AllLinks() {
		if r.Pending != "" {
			gaps++
			fmt.Fprintf(&b, "- **%s**: %s\n  %s\n", r.ID, r.Why, r.Pending)
		}
	}
	if gaps == 0 {
		b.WriteString("None.\n")
	}

	b.WriteString("\n## Tolerated\n\nMay break for a while by design: reported, and put right later as said.\n\n")
	tolerated := 0
	for _, r := range AllLinks() {
		if r.Tolerated != "" {
			tolerated++
			fmt.Fprintf(&b, "- **%s**: %s\n  %s\n", r.ID, r.Why, r.Tolerated)
		}
	}
	if tolerated == 0 {
		b.WriteString("None.\n")
	}

	b.WriteString("\n## Across sessions, packages and documents\n\nThe book's invariants (internal/features/book): checked before every commit, and here over everything stored.\n\n| rule | why |\n|---|---|\n")
	for _, inv := range book.Invariants {
		fmt.Fprintf(&b, "| %s | %s |\n", inv.ID, inv.Why)
	}

	b.WriteString("\n## Rules\n\n| rule | why | kept by |\n|---|---|---|\n")
	for _, r := range AllLinks() {
		if r.Pending != "" || r.Tolerated != "" {
			continue
		}
		kept := strings.Join(r.GuardedBy, ", ")
		if r.ByConstruction != "" {
			if kept != "" {
				kept += "; "
			}
			kept += "by construction: " + r.ByConstruction
		}
		fmt.Fprintf(&b, "| %s | %s | %s |\n", r.ID, r.Why, kept)
	}
	return b.String()
}
