package command

import (
	"fmt"
	"slices"
	"strings"
	"testing"

	"bizzy-lambda/internal/platform/statemodel"
)

// Table renders a guard table as Markdown: each guard with what it checks,
// why, what it keeps and what it offers, then each action with the guards
// that decide it. A feature keeps it as a golden file (testdata/guards.md):
// adding or changing a validation shows in review as exactly that row.
func Table[B any](title string, gs Guards[B]) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s guards\n\n", title)
	b.WriteString("Generated by the guard test (`go test -run TestGuards -update`); do not edit.\n\n")
	b.WriteString("A command is applied only if no guard on its action refuses it; a refused one changes nothing and offers the remedies.\n\n")

	b.WriteString("## Guards\n\n| guard | checks | why | keeps | remedies |\n|---|---|---|---|---|\n")
	for _, g := range gs {
		keeps := "policy: " + g.Policy
		if len(g.Protects) > 0 {
			keeps = strings.Join(g.Protects, ", ")
		}
		remedies := strings.Join(g.Remedies, ", ")
		if g.NoRemedy != "" {
			remedies = "none: " + g.NoRemedy
		}
		if len(g.Seams) > 0 {
			remedies += "; not built yet: " + strings.Join(g.Seams, ", ")
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", g.ID, strings.Join(g.On, ", "), g.Why, keeps, remedies)
	}

	b.WriteString("\n## By action\n\n| action | guards, in the order they refuse |\n|---|---|\n")
	for _, action := range gs.Actions() {
		var ids []string
		for _, g := range gs {
			if slices.Contains(g.On, action) {
				ids = append(ids, g.ID)
			}
		}
		fmt.Fprintf(&b, "| %s | %s |\n", action, strings.Join(ids, ", "))
	}
	return b.String()
}

// CheckTable lints a guard table and compares it with the golden file at
// path; `go test -run TestGuards -update` rewrites it. invariants are the
// IDs its guards may protect (see Guards.Lint).
func CheckTable[B any](t *testing.T, path, title string, gs Guards[B], invariants []string) {
	t.Helper()
	for _, err := range gs.Lint(invariants) {
		t.Error(err)
	}
	statemodel.Golden(t, path, Table(title, gs))
}
