package statemodel

import (
	"cmp"
	"fmt"
	"slices"
	"strings"
)

// Table renders an entity's state space as Markdown: the rules, then every
// combination of the axes with what the rules make of it. Combinations that
// differ only in an axis that doesn't change the outcome are merged, and the
// axis shown as `*`, so independent axes don't multiply the rows.
//
// Each feature keeps its table as a golden file (testdata/states.md):
// adding an axis or a rule shows in review as exactly the states that moved.
func Table[S any](title string, axes Axes[S], rules Rules[S]) string {
	var b strings.Builder
	fmt.Fprintf(&b, "# %s states\n\n", title)
	b.WriteString("Generated by the state test (`go test -run TestStates -update`); do not edit.\n\n")

	fmt.Fprintf(&b, "## Axes\n\n")
	for _, a := range axes {
		fmt.Fprintf(&b, "- **%s**: %s\n", a.Name, strings.Join(a.Values, ", "))
	}

	fmt.Fprintf(&b, "\n## Rules\n\n| rule | bucket | reason | why | resolved by / guarded by |\n|---|---|---|---|---|\n")
	for _, r := range rules {
		how := strings.Join(r.ResolvedBy, ", ")
		if r.Bucket == Impossible {
			parts := slices.Clone(r.GuardedBy)
			if r.ByConstruction != "" {
				parts = append(parts, "by construction: "+r.ByConstruction)
			}
			how = strings.Join(parts, "; ")
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", r.ID, r.Bucket, r.Reason, r.Why, how)
	}

	rows, counts := collapse(axes, rules)
	reachable := axes.Size() - counts[Impossible]
	fmt.Fprintf(&b, "\n## States\n\n%d combinations of the axes. %d are impossible (an impossible rule holds) and left out. "+
		"The %d reachable ones (%d contradiction, %d needs-action, %d quiet) are shown as %d rows, `*` meaning any value.\n\n",
		axes.Size(), counts[Impossible], reachable, counts[Contradiction], counts[NeedsAction], counts[Quiet], len(rows))

	b.WriteString("|")
	for _, a := range axes {
		fmt.Fprintf(&b, " %s |", a.Name)
	}
	b.WriteString(" bucket | reasons | rules |\n|")
	b.WriteString(strings.Repeat("---|", len(axes)+3))
	b.WriteString("\n")
	for _, r := range rows {
		b.WriteString("|")
		for i, v := range r.cells {
			cell := "*"
			if v >= 0 {
				cell = axes[i].Values[v]
			}
			fmt.Fprintf(&b, " %s |", cell)
		}
		fmt.Fprintf(&b, " %s | %s | %s |\n", r.bucket, r.reasons, r.rules)
	}
	return b.String()
}

type row struct {
	// cells holds each axis's value index; -1 is any value.
	cells                  []int
	bucket                 Bucket
	reasons, rules, outKey string
}

func collapse[S any](axes Axes[S], rules Rules[S]) ([]row, map[Bucket]int) {
	counts := map[Bucket]int{}
	var rows []row
	for s, idx := range axes.All() {
		out := rules.Evaluate(s)
		counts[out.Bucket]++
		if out.Bucket == Impossible {
			continue
		}
		var ids []string
		for _, r := range out.Fired {
			ids = append(ids, r.ID)
		}
		reasons := make([]string, 0)
		for _, r := range rules.Reasons(s) {
			reasons = append(reasons, string(r))
		}
		r := row{cells: idx, bucket: out.Bucket, reasons: strings.Join(reasons, ", "), rules: strings.Join(ids, ", ")}
		r.outKey = string(r.bucket) + "|" + r.reasons + "|" + r.rules
		rows = append(rows, r)
	}

	// Merge rows that agree on everything but one axis and cover all its
	// values, until nothing merges.
	for changed := true; changed; {
		changed = false
		for a := range axes {
			groups := map[string][]row{}
			var order []string
			for _, r := range rows {
				k := key(r, a)
				if _, ok := groups[k]; !ok {
					order = append(order, k)
				}
				groups[k] = append(groups[k], r)
			}
			next := make([]row, 0, len(rows))
			for _, k := range order {
				g := groups[k]
				seen := map[int]bool{}
				for _, r := range g {
					seen[r.cells[a]] = true
				}
				if len(g) > 1 && (seen[-1] || len(seen) == len(axes[a].Values)) {
					merged := g[0]
					merged.cells = slices.Clone(merged.cells)
					merged.cells[a] = -1
					next = append(next, merged)
					changed = true
					continue
				}
				next = append(next, g...)
			}
			rows = next
		}
	}

	slices.SortStableFunc(rows, func(x, y row) int {
		if c := cmp.Compare(y.bucket.severity(), x.bucket.severity()); c != 0 {
			return c
		}
		return slices.Compare(x.cells, y.cells)
	})
	return rows, counts
}

// key is a row's outcome and every cell but axis a.
func key(r row, a int) string {
	var b strings.Builder
	b.WriteString(r.outKey)
	for i, v := range r.cells {
		if i != a {
			fmt.Fprintf(&b, ",%d", v)
		}
	}
	return b.String()
}

// Lint checks a rule table is complete: every rule says how it is resolved
// or kept from happening, and fires for some state (a rule that never fires
// is dead, or its axes are missing a value).
func Lint[S any](axes Axes[S], rules Rules[S]) []error {
	var errs []error
	ids := map[string]bool{}
	for _, r := range rules {
		if ids[r.ID] {
			errs = append(errs, fmt.Errorf("rule %s: duplicate id", r.ID))
		}
		ids[r.ID] = true
		switch r.Bucket {
		case Impossible:
			if len(r.GuardedBy) == 0 && r.ByConstruction == "" {
				errs = append(errs, fmt.Errorf("rule %s: an impossible rule needs GuardedBy or ByConstruction", r.ID))
			}
			if r.Reason != "" || r.Stop {
				errs = append(errs, fmt.Errorf("rule %s: an impossible rule puts nothing on the to-do list", r.ID))
			}
		case NeedsAction, Contradiction:
			if r.Reason == "" || len(r.ResolvedBy) == 0 {
				errs = append(errs, fmt.Errorf("rule %s: a to-do rule needs a Reason and ResolvedBy", r.ID))
			}
		default:
			errs = append(errs, fmt.Errorf("rule %s: unknown bucket %q", r.ID, r.Bucket))
		}
	}

	fires := map[string]bool{}
	for s := range axes.All() {
		for _, r := range rules {
			if r.When(s) {
				fires[r.ID] = true
			}
		}
	}
	for _, r := range rules {
		if !fires[r.ID] {
			errs = append(errs, fmt.Errorf("rule %s never holds for any combination of the axes", r.ID))
		}
	}
	return errs
}

// Actions lists every action the rules name, for checking each exists.
func (rs Rules[S]) Actions() []string {
	var out []string
	for _, r := range rs {
		for _, a := range append(slices.Clone(r.ResolvedBy), r.GuardedBy...) {
			if !slices.Contains(out, a) {
				out = append(out, a)
			}
		}
	}
	slices.Sort(out)
	return out
}
